def main():
    with io.open(PATH, encoding="utf-8") as f:
        data = json.load(f)
    existing = data["questions"]
    seen = set()
    for q in existing:
        seen.add((q.get("epic"), q.get("q")))

    added = 0
    for epic, lvl, q, opts, ans, hq, hopts in NEW:
        if (epic, q) in seen:
            continue
        assert len(opts) == 4 and len(hopts) == 4, q
        assert ans in (0, 1, 2, 3), q
        entry = {"epic": epic, "level": lvl, "q": q, "options": list(opts), "answer": ans}
        entry["tr"] = {"hi": {"q": hq, "options": list(hopts)}}
        existing.append(entry)
        seen.add((epic, q))
        added += 1

    data["_help"] = ("Add questions to the list below. epic: M = Mahabharata, R = Ramayana, "
                     "V = Vedas, P = Puranas. level: 1 = Initiate, 2 = Warrior, 3 = Maharathi (Scholar). "
                     "options: exactly 4 choices. answer: position of the correct option, 0 to 3 (0 = first). "
                     "The game shuffles the options itself. No server restart needed for new matches. "
                     "OPTIONAL TRANSLATION: add \"tr\":{\"hi\":{\"q\":\"...\",\"options\":[4 items in the SAME order as the English options]}} "
                     "to a question; codes: hi, mr, sa, ta, te. Players of that language then see it translated; otherwise English.")
    with io.open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print("Added %d questions. Total now %d." % (added, len(existing)))

if __name__ == "__main__":
    main()
